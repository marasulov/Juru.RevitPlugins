namespace Juru.RevitPlugins.Openings.Models.Server;

/// <summary>
/// Итог сопоставления заданий файла с тем, что о них уже знает сервер -
/// см. <see cref="TaskKeyReconciler"/>.
/// </summary>
public class TaskKeyAdoptionResult {
    /// <summary>
    /// Сколько заданий этой дисциплины сервер знает по этому объекту.
    /// </summary>
    /// <remarks>
    /// Ноль при непустом файле - это не "всё сошлось", а "сверять было не с чем": сервер не отдаёт
    /// заданий по объекту. Молча это выглядит как исправная работа, поэтому попадает в отчёт.
    /// </remarks>
    public int ServerTasks { get; set; }

    /// <summary>
    /// Задания, получившие ключ ранее выданного задания на том же месте.
    /// </summary>
    public int Adopted { get; set; }

    /// <summary>
    /// Задания, у которых кандидаты на сервере нашлись, но однозначной пары не вышло: рядом стоит
    /// другое задание или на то же место претендуют несколько. Уходят с новым ключом.
    /// </summary>
    public int Ambiguous { get; set; }

    /// <summary>
    /// Задания, в семействе которых нет параметра ключа: семейство устарело, нужно перезагрузить.
    /// </summary>
    public int MissingParameter { get; set; }

    /// <summary>
    /// Задания, у которых параметр ключа есть, но записать в него нельзя: он только для чтения
    /// (в семействе задан формулой или заведён как параметр типа) либо Revit отказался от значения.
    /// Считается отдельно от <see cref="MissingParameter"/>: лечится это по-разному, а внешне
    /// и то, и другое выглядит одинаково - "ключ пустой после отправки".
    /// </summary>
    public int NotWritable { get; set; }
}
