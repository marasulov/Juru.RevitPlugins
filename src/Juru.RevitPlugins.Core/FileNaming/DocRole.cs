namespace Juru.RevitPlugins.Core.FileNaming;

/// <summary>
/// Роль файла в обмене заданиями на отверстия.
/// </summary>
public enum DocRole {
    /// <summary>
    /// Роль не определена: имя файла не соответствует стандарту либо его дисциплина в обмене не участвует.
    /// </summary>
    Unknown,

    /// <summary>
    /// Файл инженерных систем - источник заданий на отверстия.
    /// </summary>
    Mep,

    /// <summary>
    /// Файл архитектуры - получатель заданий, размещает чистовые отверстия.
    /// </summary>
    Arc,

    /// <summary>
    /// Файл несущих конструкций - получатель заданий, размещает чистовые отверстия.
    /// </summary>
    Str
}
