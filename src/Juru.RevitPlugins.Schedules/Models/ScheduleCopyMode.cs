namespace Juru.RevitPlugins.Schedules.Models;

/// <summary>
///     Чем становится английский вид отмеченных спецификаций. Оригинал не трогается ни в том, ни в
///     другом случае: перевод всегда ложится в новую таблицу.
/// </summary>
public enum ScheduleCopyMode
{
    /// <summary>
    ///     Копия чертёжным видом: таблица рисуется заново линиями и надписями модели.
    /// </summary>
    RedrawAsLines,

    /// <summary>
    ///     Копия спецификацией: переведённая таблица выкладывается в шапку новой спецификации теми же
    ///     строками и колонками. Копия остаётся спецификацией - и в диспетчере, и на листе.
    /// </summary>
    CopyAsSchedule
}
